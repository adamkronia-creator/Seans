export const CASE_ICON_GROUPS = (Object.keys(CATEGORY_LABELS) as (keyof typeof catalog)[]).map((category) => ({
  title: CATEGORY_LABELS[category],
  icons: catalog[category].map((name) => {
    const id: SolarBoldIconId = `solar:${category}/${name}`;
    return {
      id,
      label: LOCAL_LABELS[id] ?? name.replace(/-/g, ' '),
      href: `${import.meta.env.BASE_URL}solar-bold/${category}.svg#${name}`,
    };
  }),
}));

const byId = new Map(CASE_ICON_GROUPS.flatMap(({ icons }) => icons.map((icon) => [icon.id, icon] as const)));

export function caseIcon(id: CaseIconId | null | undefined) {
  if (!id) return undefined;
  const legacy = Object.prototype.hasOwnProperty.call(LEGACY_ICONS, id) ? LEGACY_ICONS[id as keyof typeof LEGACY_ICONS] : undefined;
  return byId.get(legacy ?? id as SolarBoldIconId);
}
