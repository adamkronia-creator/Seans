export type CaseIconId =
  | 'general'
  | 'anamnesis'
  | 'request'
  | 'hypothesis'
  | 'structure'
  | 'signifiers'
  | 'scenario'
  | 'transfer';

export type CaseRowIconId = 'client' | 'birthday' | 'calendar' | 'clock' | 'format';

export type CaseBlock =
  | { type: 'p'; text: string }
  | { type: 'ul'; items: string[] };

export interface CaseSection {
  id: string;
  title: string;
  icon: CaseIconId;
  /** Цвет шапки: blue — стандартный, brown — клиническая гипотеза */
  tone: 'blue' | 'brown';
  /** Для «Общей информации»: строки «название — значение» */
  rows?: { icon: CaseRowIconId; label: string; value: string }[];
  /** Для текстовых разделов */
  blocks?: CaseBlock[];
  /** Дата последнего обновления (для текстовых разделов) */
  updated?: string;
}

