/** Заключение по результату прохождения: баллы вместо условных, остальное (диапазоны, расшифровки) то же, что в примере */
function withScores(base: ConclusionData, scores: Record<string, number>, info: ConclusionData['info'], validity?: ConclusionData['validity']): ConclusionData {
  return { ...base, info, validity, scales: base.scales.map((s) => ({ ...s, score: scores[s.code] })) };
}

/** СМОЛ: Т-баллы по шкалам и вывод по контрольным шкалам */
export function smolResult(scores: Record<string, number>, info: ConclusionData['info'], validity: ConclusionData['validity']): ConclusionData {
  return withScores(SMOL, scores, info, validity);
}

/** BDI: общая сумма (шкала «Депрессия») и две подшкалы */
export function bdiResult(score: { total: number; cognitive: number; somatic: number }, info: ConclusionData['info']): ConclusionData {
  const [main, cognitive, somatic] = BDI.scales;
  return withScores(BDI, { [main.code]: score.total, [cognitive.code]: score.cognitive, [somatic.code]: score.somatic }, info);
}

/** BHS: сумма баллов безнадёжности */
export function bhsResult(score: number, info: ConclusionData['info']): ConclusionData {
  return withScores(BHS, { [BHS.scales[0].code]: score }, info);
}

/** GAD-7: сумма баллов тревожности */
export function gad7Result(score: number, info: ConclusionData['info']): ConclusionData {
  return withScores(GAD7, { [GAD7.scales[0].code]: score }, info);
}

/** PHQ-9: сумма баллов депрессии и предупреждение, если на девятый вопрос ответили не «Совсем нет» */
export function phq9Result(score: Phq9Scores, info: ConclusionData['info']): ConclusionData {
  return { ...withScores(PHQ9, { [PHQ9.scales[0].code]: score.total }, info), alert: suicidalAlert(score.suicidal) };
}

/** SQ: баллы десяти шкал в порядке шкал: Дм, Зс, Пд, Вз, Гт, Дс, Тр, Эк, Эм, Цк */
export function sqResult(scores: number[], info: ConclusionData['info']): ConclusionData {
  return withScores(SQ, byOrder(SQ, scores), info);
}

/** ИТО: баллы в порядке шкал (Эк, Сп, Аг, Рг, Ин, Сз, Тр, Лб, Ис, Агг); вывод о достоверности зависит от двух последних шкал */
export function itoResult(scores: number[], info: ConclusionData['info']): ConclusionData {
  const values = byOrder(ITO, scores);
  const limit = ITO.extra!.levels[0].to;
  const ok = values['Ис'] <= limit && values['Агг'] <= limit;
  const validity = ok
    ? ITO.validity
    : { ok: false, text: 'Достоверность ответов снижена — профиль следует интерпретировать с осторожностью.' };
  return withScores(ITO, values, info, validity);
}

/** ОСР: «Вероятность» (0–29) и девять факторов в порядке шкал: Дм, Аф, Ун, Нс, СП, СК, Мк, ВП, АС */
export function osrResult(score: { total: number; factors: number[] }, info: ConclusionData['info']): ConclusionData {
  return withScores(OSR, byOrder(OSR, [score.total, ...score.factors]), info);
}

