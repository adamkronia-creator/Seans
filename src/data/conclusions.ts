/** Предупреждение психологу, если на пункт 15 SCL-90 («Мысли о том, чтобы покончить с собой») ответили не «Совсем нет» */
function scl90Alert(answer: number | undefined): string | undefined {
  if (!answer) return undefined;
  return `Пункт 15 («Мысли о том, чтобы покончить с собой»): отмечен ответ «${SCL90_ANSWERS[answer]}». Независимо от баллов по шкалам необходимо уточнить суицидальный риск.`;
}

/** Число с десятичной запятой для подписей диапазонов: «1,1» */
const dec = (n: number) => String(n).replace('.', ',');

/**
 * Два диапазона SCL-90: норма и выше нормы. Верхняя граница нормы у каждой шкалы своя (из настроек теста).
 * Шкалы считаются до сотых, поэтому «выше нормы» начинается со следующей сотой (у PST — со следующего целого).
 */
function normLevels(norm: number, max: number, step = 0.01): ConclusionLevel[] {
  const next = Math.round((norm + step) * 100) / 100;
  return [
    { key: 'norm', from: 0, to: norm, range: `0 — ${dec(norm)}`, legend: 'Норма', chip: 'Норма', tone: 'green', verdictPre: 'является ', verdict: 'нормативным', verdictPost: ' показателем' },
    { key: 'high', from: next, to: max, range: `${dec(next)} — ${dec(max)}`, legend: 'Выше нормы', chip: 'Выше нормы', tone: 'red', verdictPre: 'является ', verdict: 'повышенным', verdictPost: ' показателем, выходящим за рамки нормативного диапазона' },
  ];
}

