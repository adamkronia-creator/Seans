/*
 * Примеры заключений: условный результат клиента (мужская форма), по которому показаны все шкалы
 * и расшифровка диапазонов, как увидит психолог. Структура общая для всех тестов.
 */

export type LevelTone = 'green' | 'yellow' | 'orange' | 'red' | 'darkred';

/** Диапазон баллов шкалы: границы, подписи и цвет */
export interface ConclusionLevel {
  key: string;
  from: number;
  to: number;
  /** Подпись диапазона в заголовке расшифровки: «40 — 69» */
  range: string;
  /** Подпись в легенде диаграммы и в чипе расшифровки */
  legend: string;
  chip: string;
  tone: LevelTone;
  /** Заголовок диапазона в расшифровке вместо «<chip> показатель», если так название не читается («Заострение черты») */
  heading?: string;
  /** «…что» + verdictPre + выделенное verdict + verdictPost */
  verdictPre: string;
  verdict: string;
  verdictPost: string;
}

export interface ConclusionScale {
  code: string;
  name: string;
  group: 'main' | 'extra';
  score: number;
  /** Максимум шкалы */
  max: number;
  /** Делится ли шкала на диапазоны (иначе только баллы) */
  leveled: boolean;
  /** Название шкалы в диаграммах общего обзора: «Шкала ипохондрии» */
  chartName?: string;
  /** Что измеряет шкала (продолжение после «—») */
  about: string;
  /** Ключ блока диаграммы (из `blocks`), если шкалы собраны в блоки */
  block?: string;
  /** Свои диапазоны и подписи оси, если у шкалы они отличаются от общих (у SCL-90 у каждой шкалы своя граница нормы) */
  levels?: ConclusionLevel[];
  ticks?: number[];
}

export interface ConclusionData {
  /** Возраст есть не всегда: при самостоятельном прохождении его не спрашивают, строка тогда скрыта */
  info: { date: string; time: string; duration: string; age?: string };
  /** Карточки шкал в виде СМОЛ: полоса с границами диапазонов, расшифровка с «Читать далее» */
  flat?: boolean;
  /** Показывать ли общие диаграммы основных и дополнительных шкал и метки «Шкала …» */
  overview: boolean;
  /** Максимум шкал с диапазонами */
  max: number;
  levels: ConclusionLevel[];
  /** Подписи оси диаграммы */
  ticks: number[];
  scales: ConclusionScale[];
  /** Расшифровка: код шкалы → ключ диапазона → абзацы */
  interpretation: Record<string, Record<string, string[]>>;
  /** Одна общая диаграмма всех шкал («Шкалы тестирования») при `overview: false`; все полосы на оси 0–max */
  summary?: boolean;
  /** Блоки диаграмм вместо общих: у каждого свой заголовок и шкалы с `block` = ключу; под столбцами подписи оси, внизу маркеры диапазонов */
  blocks?: { key: string; title: string }[];
  /** Вывод по контрольным шкалам: согласованность ответов и возможность интерпретации */
  validity?: { ok: boolean; text: string };
  /** Своя система диапазонов для дополнительных шкал, если она отличается от общей (у ИТО: «достоверно / не достоверно») */
  extra?: { max: number; ticks: number[]; levels: ConclusionLevel[] };
  /** Предупреждение психологу над шкалами (например, ответ о суицидальных мыслях в PHQ-9); нет, если тревожных ответов не было */
  alert?: string;
  /** Подпись оси под каждой полосой (в блоках и общей диаграмме), если у шкал разная длина */
  axisEach?: boolean;
}

/** Диапазоны шкалы: свои, если заданы, иначе общие */
export const levelsOf = (data: ConclusionData, scale?: ConclusionScale): ConclusionLevel[] => scale?.levels ?? data.levels;

export const levelOf = (data: ConclusionData, score: number, scale?: ConclusionScale): ConclusionLevel => {
  const levels = levelsOf(data, scale);
  return levels.find((l) => score >= l.from && score <= l.to) ?? levels[levels.length - 1];
};

