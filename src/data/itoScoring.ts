import { ITO_ANSWERS } from './testBlank';

/*
 * Подсчёт индивидуально-типологического опросника (ИТО, Л. Н. Собчик, 91 утверждение).
 *
 * У каждой шкалы свой ключ: утверждения, за ответ «Верно» (+) на которые шкала получает балл, и утверждения, за ответ
 * «Неверно» (−) на которые она получает балл. Каждое совпадение с ключом — один балл. У всех шкал по 9 утверждений,
 * поэтому значения от 0 до 9.
 *
 * Восемь основных шкал: экстраверсия, спонтанность, агрессивность, ригидность, интроверсия, сензитивность,
 * тревожность, лабильность. Две дополнительные проверяют достоверность: «Шкала искренности» (в ключе источников — «Ложь»:
 * стремление приукрасить себя) и «Шкала аггравации» (преувеличение своих проблем). Первое утверждение («Я постараюсь
 * отнестись к исследованию ответственно…») в баллы не входит. 91-е утверждение («Я отвечал на все вопросы очень
 * правдиво») засчитывается в аггравацию за ответ «Неверно» — так ключ приведён в полном издании на 91 утверждение.
 *
 * Границы уровней основных шкал (0–1, 2–4, 5–7, 8–9) и дополнительных (0–5, 6–9) заданы в настройках теста.
 */

const TRUE = ITO_ANSWERS.indexOf('Верно');
const FALSE = ITO_ANSWERS.indexOf('Неверно');

interface Key {
  /** Утверждения (с 1), за ответ «Верно» на которые шкала получает балл */
  yes: number[];
  /** Утверждения (с 1), за ответ «Неверно» на которые шкала получает балл */
  no: number[];
}

/** Шкалы в порядке заключения: Эк, Сп, Аг, Рг, Ин, Сз, Тр, Лб, затем Ис и Агг */
export const ITO_KEYS: Key[] = [
  { yes: [12, 27, 29, 42, 44, 72], no: [14, 57, 87] }, // Экстраверсия
  { yes: [4, 19, 21, 34, 49, 50], no: [6, 65, 80] }, // Спонтанность
  { yes: [7, 22, 36, 37, 51, 53, 68], no: [66, 81] }, // Агрессивность
  { yes: [9, 24, 26, 39, 41, 56], no: [71, 83, 86] }, // Ригидность
  { yes: [3, 5, 33, 35, 48, 78], no: [18, 20, 63] }, // Интроверсия
  { yes: [15, 28, 43, 59, 89], no: [11, 13, 30, 74] }, // Сензитивность
  { yes: [8, 23, 38, 52, 54, 69, 84], no: [67, 82] }, // Тревожность
  { yes: [10, 25, 40, 55, 58], no: [70, 73, 85, 88] }, // Лабильность
  { yes: [16, 31, 45, 46, 60, 61, 75, 76, 90], no: [] }, // Шкала искренности
  { yes: [2, 17, 32, 47, 62, 64, 77, 79], no: [91] }, // Шкала аггравации
];

/** Баллы десяти шкал в порядке заключения; неотвеченные утверждения баллов не дают */
export function scoreIto(answers: ReadonlyArray<number | undefined>): number[] {
  return ITO_KEYS.map(
    ({ yes, no }) => yes.filter((n) => answers[n - 1] === TRUE).length + no.filter((n) => answers[n - 1] === FALSE).length,
  );
}
