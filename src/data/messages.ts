import { clientResultPath } from './resultLinks';

export interface Message {
  id: string;
  from: 'me' | 'them';
  text: string;
  time: string;
  /** Статус исходящего; у старых сообщений считается «прочитано» */
  status?: 'sending' | 'sent' | 'read';
  /** Ответ на сообщение с этим id */
  replyTo?: string;
  /** Карточка теста (id из библиотеки): аватарка, название, подпись и кнопка под сообщением */
  test?: string;
  /** Подпись карточки: «Присланный тест» (отправлен клиенту, кнопка «Пройти») или «Пройденный тест» (кнопка «Посмотреть»); без значения — присланный */
  testKind?: 'sent' | 'passed';
  /** Кнопки под пузырём, как у ботов в Telegram */
  buttons?: MessageButton[];
}

export interface MessageButton {
  label: string;
  /** Адрес внутри приложения (hash-маршрут без «#»), например «/chat/favorites/result/r1» */
  href: string;
}

export interface MessageGroup {
  /** Подпись разделителя дня */
  label: string;
  messages: Message[];
}

