/**
 * Тесты, у которых «Особенности тестирования» уже в новом виде: короткие названия строк и «?» с подсказкой вместо описаний.
 * Пока это пробный запуск на СМОЛ; когда его одобрят, список заменяется проверкой «для всех».
 */
const PILOT_TESTS = new Set(['smol']);

export const hasOptionHelp = (testId: string) => PILOT_TESTS.has(testId);

/** Название настройки «Сохранить бланк» на экране теста и в окне настроек отправленного теста: в новом виде оно длиннее */
export const saveBlankLabel = (testId?: string) => (testId && hasOptionHelp(testId) ? 'Сохранить заполненный бланк' : 'Сохранить бланк');
