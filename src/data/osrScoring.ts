import { OCR_ANSWERS } from './testBlank';

/*
 * Подсчёт опросника суицидального риска (ОСР, модификация Т. Н. Разуваевой).
 *
 * 29 утверждений, на каждое отвечают «Верно» (+) или «Неверно» (−). Девять факторов считаются так: берутся утверждения
 * фактора, за каждое совпадение с ключом — один балл; сумма умножается на индекс фактора и округляется вверх до целого.
 * Так же округлены максимумы факторов (6 / 6,6 / 6 / 7,5 / 6 / 6,9 / 6,4 / 6,6 / 6,4), поэтому в настройках теста шкалы
 * заданы как 0–6, 0–7, 0–6, 0–8, 0–6, 0–7, 0–7, 0–7, 0–7.
 *
 * Ключ взят из описания методики. В нём не указан знак ответа для утверждения 16 («В вашей жизни не было таких неудач,
 * когда казалось, что всё кончено»): балл максимализма даёт «Неверно» — такие неудачи были.
 *
 * «Вероятность» (Вер, 0–29) — число ответов, указывающих на риск, по всем 29 утверждениям. Для утверждений 16, 17 и 19
 * (неудачи, из-за которых «всё кончено»; удовлетворённость судьбой; привязанность к людям) это «Неверно», для остальных —
 * «Верно». Границы уровней 0–9 / 10–17 / 18–29 заданы в настройках теста.
 */

const YES = OCR_ANSWERS.indexOf('Верно');
const NO = OCR_ANSWERS.indexOf('Неверно');

interface Factor {
  /** Утверждения (с 1), за которые балл даёт «Верно» */
  yes: number[];
  /** Утверждения (с 1), за которые балл даёт «Неверно» */
  no?: number[];
  /** Индекс фактора в десятых долях: 12 — это 1,2 */
  index: number;
}

/** Факторы в порядке шкал заключения: Дм, Аф, Ун, Нс, СП, СК, Мк, ВП, АС */
const FACTORS: Factor[] = [
  { yes: [12, 14, 20, 22, 27], index: 12 }, // Демонстративность, максимум 6
  { yes: [1, 10, 20, 23, 28, 29], index: 11 }, // Аффективность, 6,6
  { yes: [1, 12, 14, 22, 27], index: 12 }, // Уникальность, 6
  { yes: [2, 3, 6, 7, 21], index: 15 }, // Несостоятельность, 7,5
  { yes: [5, 11, 13, 15, 22, 25], index: 10 }, // Социальный пессимизм, 6
  { yes: [8, 9, 18], index: 23 }, // Слом культурных барьеров, 6,9
  { yes: [4], no: [16], index: 32 }, // Максимализм, 6,4
  { yes: [2, 3, 12, 24, 26, 27], index: 11 }, // Временная перспектива, 6,6
  { yes: [17, 19], index: 32 }, // Антисуицидальный фактор, 6,4
];

/** Утверждения, где на риск указывает «Неверно» */
const RISK_IF_NO = [16, 17, 19];

const STATEMENTS = 29;

export interface OsrScores {
  /** Вероятность, 0–29 */
  total: number;
  /** Факторы в порядке шкал заключения (Дм … АС), целые баллы */
  factors: number[];
}

/** Подсчёт ОСР; неотвеченные утверждения баллов не дают */
export function scoreOsr(answers: ReadonlyArray<number | undefined>): OsrScores {
  const said = (n: number, answer: number) => answers[n - 1] === answer;

  const factors = FACTORS.map((f) => {
    const hits = f.yes.filter((n) => said(n, YES)).length + (f.no ?? []).filter((n) => said(n, NO)).length;
    // Вверх до целого; целочисленная арифметика, чтобы не терять 6,0 из-за дробей
    return Math.floor((hits * f.index + 9) / 10);
  });

  let total = 0;
  for (let n = 1; n <= STATEMENTS; n++) {
    if (said(n, RISK_IF_NO.includes(n) ? NO : YES)) total++;
  }
  return { total, factors };
}
