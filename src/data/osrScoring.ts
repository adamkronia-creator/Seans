import { OCR_ANSWERS } from './testBlank';

/*
 * Подсчёт опросника суицидального риска (ОСР, модификация Т. Н. Разуваевой).
 *
 * 29 утверждений, на каждое отвечают «Верно» (+) или «Неверно» (−). Балл во всех факторах и в общем показателе дают
 * только ответы «Верно» (+), в том числе на утверждение 16 («В вашей жизни не было таких неудач, когда казалось, что всё
 * кончено») — так считает эталонная онлайн-версия методики.
 *
 * Девять факторов: берутся утверждения фактора, за каждое «Верно» — один балл; сумма умножается на индекс фактора.
 * Результат не округляется и показывается с десятыми, как в самой методике: 3,2; 6,6; 7,5.
 * Максимумы факторов — 6 / 6,6 / 6 / 7,5 / 6 / 6,9 / 6,4 / 6,6 / 6,4.
 *
 * «Вероятность» (Вер, 0–29) — число ответов «Верно» по всем 29 утверждениям. Границы уровней 0–9 / 10–17 / 18–29 заданы
 * в настройках теста.
 */

const YES = OCR_ANSWERS.indexOf('Верно');

interface Factor {
  /** Утверждения (с 1), за каждое «Верно» фактор получает балл */
  items: number[];
  /** Индекс фактора в десятых долях: 12 — это 1,2 */
  index: number;
}

/** Факторы в порядке шкал заключения: Дм, Аф, Ун, Нс, СП, СК, Мк, ВП, АС */
const FACTORS: Factor[] = [
  { items: [12, 14, 20, 22, 27], index: 12 }, // Демонстративность, максимум 6
  { items: [1, 10, 20, 23, 28, 29], index: 11 }, // Аффективность, 6,6
  { items: [1, 12, 14, 22, 27], index: 12 }, // Уникальность, 6
  { items: [2, 3, 6, 7, 21], index: 15 }, // Несостоятельность, 7,5
  { items: [5, 11, 13, 15, 22, 25], index: 10 }, // Социальный пессимизм, 6
  { items: [8, 9, 18], index: 23 }, // Слом культурных барьеров, 6,9
  { items: [4, 16], index: 32 }, // Максимализм, 6,4
  { items: [2, 3, 12, 24, 26, 27], index: 11 }, // Временная перспектива, 6,6
  { items: [17, 19], index: 32 }, // Антисуицидальный фактор, 6,4
];

const STATEMENTS = 29;

export interface OsrScores {
  /** Вероятность: число ответов «Верно», 0–29 */
  total: number;
  /** Факторы в порядке шкал заключения (Дм … АС): число «Верно» × индекс, с десятыми */
  factors: number[];
}

/** Подсчёт ОСР; неотвеченные утверждения баллов не дают */
export function scoreOsr(answers: ReadonlyArray<number | undefined>): OsrScores {
  const agreed = (n: number) => answers[n - 1] === YES;

  // Индекс в десятых долях: целое произведение делим на 10 — так 3 × 1,1 даёт ровно 3,3, а не 3,3000000000000003
  const factors = FACTORS.map((f) => (f.items.filter(agreed).length * f.index) / 10);

  let total = 0;
  for (let n = 1; n <= STATEMENTS; n++) if (agreed(n)) total++;
  return { total, factors };
}
