/** Человек для списков: то, что нужно строке (фото, имя, подпись, город) */
export interface Person {
  id: string;
  name: string;
  avatar?: string;
  headline: string;
  city: string;
}

/** Профиль человека для страницы: у собеседника из чатов он лежит в `PERSON_PROFILES`, у остальных в каталоге */
export function profileOf(id: string): PersonProfile | undefined {
  return PERSON_PROFILES[id] ?? DIRECTORY[id];
}

/** Человек по идентификатору: сначала чаты (имя и фото могли поменять), потом каталог. Ваш собственный профиль сюда не входит */
export function personOf(id: string, chats: readonly Chat[]): Person | undefined {
  const chat = chats.find((c) => c.id === id);
  const info = profileOf(id);
  if (chat) return { id, name: chat.name, avatar: chat.avatar, headline: info?.headline ?? '', city: info?.city ?? '' };
  const entry = DIRECTORY[id];
  return entry ? { id, name: entry.name, headline: entry.headline, city: entry.city } : undefined;
}

/** Есть ли чат с этим человеком (по нему «Написать» открывает чат, а не заводит новый) */
export const hasChat = (id: string, chats: readonly Chat[]): boolean => chats.some((c) => c.id === id);
