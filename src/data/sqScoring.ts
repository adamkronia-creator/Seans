import { SQ_ANSWERS } from './testBlank';

/*
 * Подсчёт опросника Леонгарда — Шмишека (SQ, 88 вопросов).
 *
 * У каждой из десяти шкал свой ключ: вопросы, на которые балл даёт ответ «Да» (+), и вопросы, на которые балл даёт
 * ответ «Нет» (−). Число совпадений с ключом умножается на коэффициент шкалы (2, 3 или 6), поэтому у всех шкал
 * максимум 24 балла: значения кратны коэффициенту (0, 2, 4 … 24; 0, 3, 6 … 24; у «Экзальтированности» 0, 6, 12, 18, 24).
 * Границы уровней (0–6, 7–18, 19–24) заданы в настройках теста.
 */

const YES = SQ_ANSWERS.indexOf('Да');
const NO = SQ_ANSWERS.indexOf('Нет');

interface Key {
  /** Вопросы (с 1), за ответ «Да» на которые шкала получает балл */
  yes: number[];
  /** Вопросы (с 1), за ответ «Нет» на которые шкала получает балл */
  no: number[];
  /** Коэффициент шкалы */
  k: number;
}

/** Шкалы в порядке заключения: Дм, Зс, Пд, Вз, Гт, Дс, Тр, Эк, Эм, Цк */
export const SQ_KEYS: Key[] = [
  { yes: [7, 19, 22, 29, 41, 44, 63, 66, 73, 85, 88], no: [51], k: 2 }, // Демонстративность
  { yes: [2, 15, 24, 34, 37, 56, 68, 78, 81], no: [12, 46, 59], k: 2 }, // Застревание
  { yes: [4, 14, 17, 26, 39, 48, 58, 61, 70, 80, 83], no: [36], k: 2 }, // Педантичность
  { yes: [8, 20, 30, 42, 52, 64, 74, 86], no: [], k: 3 }, // Возбудимость
  { yes: [1, 11, 23, 33, 45, 55, 67, 77], no: [], k: 3 }, // Гипертимность
  { yes: [9, 21, 43, 75, 87], no: [31, 53, 65], k: 3 }, // Дистимность
  { yes: [16, 27, 38, 49, 60, 71, 82], no: [5], k: 3 }, // Тревожность
  { yes: [10, 32, 54, 76], no: [], k: 6 }, // Экзальтированность
  { yes: [3, 13, 35, 47, 57, 69, 79], no: [25], k: 3 }, // Эмотивность
  { yes: [6, 18, 28, 40, 50, 62, 72, 84], no: [], k: 3 }, // Циклотимность
];

/** Баллы десяти шкал в порядке заключения; неотвеченные вопросы баллов не дают */
export function scoreSq(answers: ReadonlyArray<number | undefined>): number[] {
  return SQ_KEYS.map(({ yes, no, k }) => {
    const hits = yes.filter((n) => answers[n - 1] === YES).length + no.filter((n) => answers[n - 1] === NO).length;
    return hits * k;
  });
}
