/*
 * Содержимое экрана «Настройка задания»: описание, цель, анализ материалов, бланк и пример выполнения.
 * Пока есть данные только у задания «Что я должен?»; у остальных экран настроек не открывается.
 */

export interface TaskSettingsData {
  /** Описание задания; пустая строка между абзацами */
  intro: string;
  /** Начало описания, выделенное полужирным */
  lead?: string;
  /** «Цель задания» */
  goal: string;
  /** «Анализ материалов»; пустая строка между абзацами */
  analysis: string;
  /** Количество предложений в бланке */
  sentences: number;
  duration: string;
  age: string;
  /** Формы бланка: первая выбрана по умолчанию */
  forms: string[];
  /** Сообщение клиенту по умолчанию */
  message: string;
  /** Бланк: правила, начала предложений по формам, шкала состояния */
  blank: TaskBlank;
  /** Пример выполнения по формам */
  example: TaskExample;
}

export interface TaskBlank {
  rules: string[];
  /** Начала предложений для каждой формы бланка (мужская / женская) */
  starters: Record<string, string[]>;
  /** Шкала «Как вы себя чувствуете?»: от худшего к лучшему */
  state: string[];
  /** Подсказка над полем комментария */
  commentHint: string;
}

export interface TaskExample {
  /** Продолжения предложений: по одному на начало из бланка */
  answers: Record<string, string[]>;
  comment: Record<string, string>;
  /** Номер выбранного состояния */
  state: number;
  /** Что можно отметить психологу при разборе примера */
  notes: string[];
}

