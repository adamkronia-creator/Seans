/*
 * Содержимое экрана «Настройка теста». Подробный макет есть только у BDI;
 * у остальных тестов известны лишь название и краткое описание из библиотеки,
 * поэтому остальные блоки для них не показываются, пока нет данных.
 */

export type ScoreTone = 'green' | 'yellow' | 'orange' | 'red';

export interface TestSettingsData {
  /** Описание теста; пустая строка между абзацами, «●» — маркер списка, как в макете */
  intro: string;
  /** Начало описания, выделенное полужирным (название методики) */
  lead?: string;
  /** Названия шкал */
  scales?: { main: string[]; extra: string[] };
  /** Система баллов: диапазон, пояснение и цвет точки */
  scoring?: { range: string; label: string; tone: ScoreTone }[];
  questions?: number;
  duration?: string;
  age?: string;
  /** Формы бланка: первая выбрана по умолчанию */
  forms?: string[];
  /** Сообщение клиенту по умолчанию */
  message: string;
}

