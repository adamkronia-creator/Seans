/*
 * Неразрывные пробелы по правилам русской типографики. Применяется только при показе длинных текстов (описание заданий,
 * инструкция, подсказки), а сами тексты в данных остаются с обычными пробелами. Работает и в браузере, и в Node (на нём
 * этот файл проверяет scripts/test-library.mjs).
 *
 *   — предлоги, союзы и короткие слова не остаются в конце строки: «в парке», «от 0 до 10»;
 *   — частицы «бы», «же», «ли» держатся за словом перед собой;
 *   — число не отрывается от слова: «15 минут»;
 *   — тире не переносится в начало строки: «задание — это»;
 *   — короткое слово с дефисом («что-то», «из-за») и диапазон («5–10») не рвутся на два конца строки; длинное
 *     («когнитивно-поведенческая») переносится по дефису, иначе предыдущая строка оставалась бы наполовину пустой.
 */

const NBSP = '\u00A0';
/** Невидимая «склейка слов»: запрещает перенос в этом месте (поддерживается браузерами, шрифт ей не нужен) */
const WORD_JOINER = '\u2060';
const LETTER = 'А-Яа-яЁёA-Za-z0-9';

/** Слова, которые прижимаются к следующему: предлоги, союзы и отрицания из одной-двух букв. Слова из трёх букв и длиннее не трогаем: на узком экране цепочка из нескольких слов даёт рваные строки. После дефиса слово не считается («что-то» — одно слово) */
const SHORT = new RegExp(`(^|[^${LETTER}-])(а|в|и|к|о|с|у|я|во|да|до|за|из|ко|на|не|ни|но|об|от|по|со|то)[ \\t]+(?=\\S)`, 'gi');
/** Частица прижимается к слову перед ней */
const PARTICLE = new RegExp(`[ \\t]+(бы|же|ли|ль)(?![${LETTER}])`, 'gi');
const DASH = /[ \t]+—/g;
const NUMBER = /(\d)[ \t]+(?=[А-Яа-яЁё%])/g;
/** Слово с дефисом («что-то», «чём-то») целиком; не длиннее этого — не рвём */
const COMPOUND = /[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)+/g;
const COMPOUND_MAX = 12;
/** «5–10»: после среднего тире между цифрами переноса нет */
const RANGE = /(\d)–(?=\d)/g;

/** Текст с неразрывными пробелами; повторный вызов ничего не меняет */
export function typo(text: string): string {
  let out = text;
  // Два прохода: слово, стоящее сразу за коротким («и в парке»), в первом проходе осталось без своего «начала»
  for (let pass = 0; pass < 2; pass++) out = out.replace(SHORT, `$1$2${NBSP}`);
  return out
    .replace(PARTICLE, `${NBSP}$1`)
    .replace(DASH, `${NBSP}—`)
    .replace(NUMBER, `$1${NBSP}`)
    .replace(COMPOUND, (word) => (word.length <= COMPOUND_MAX ? word.split('-').join(`-${WORD_JOINER}`) : word))
    .replace(RANGE, `$1–${WORD_JOINER}`);
}
